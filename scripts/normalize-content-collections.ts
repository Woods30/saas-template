/**
 * 规范化 content-collections 生成物首行注释。
 *
 * `@content-collections/core` 在 index.js 首行写入 `new Date()`，使该文件每次
 * 构建都变（噪音 diff）。这里把时间戳剥掉，只留固定标识。仅 index.js 带此头，
 * 其余 all*.js 不受影响。
 */
import { readFileSync, writeFileSync } from 'node:fs'

const HEADER_RE = /^\/\/ generated by content-collections at .*$/m
const FIXED_HEADER = '// generated by content-collections'

/** 生成物 index.js 的相对路径（cwd 为仓库根）。 */
export const GENERATED_INDEX_PATH = '.content-collections/generated/index.js'

/** 把首行带时间戳的生成头替换为固定串；无头或已是固定串则原样返回。 */
export function normalizeHeader(content: string): string {
  return content.replace(HEADER_RE, FIXED_HEADER)
}

/**
 * 读取生成物、规范化首行，仅在内容变化时写回。
 *
 * 文件不存在时静默返回 false（首次内容构建前调用不应抛错）。
 * `after !== before` 的写回守卫同时是 dev 轮询避免「写 → 触发变更 → 再写」
 * 死循环的关键：`normalizeHeader` 幂等，已规范化的内容不会再次落盘。
 *
 * @returns 是否发生了写回
 */
export function normalizeGeneratedFile(path: string = GENERATED_INDEX_PATH): boolean {
  let before: string
  try {
    before = readFileSync(path, 'utf-8')
  } catch {
    return false
  }
  const after = normalizeHeader(before)
  if (after === before) return false
  writeFileSync(path, after)
  return true
}

// CLI 入口：仅 `tsx scripts/normalize-content-collections.ts` 触发；被 vite.config.ts
// 或测试 import 时 `process.argv[1]` 不以该文件名结尾，故不会执行（无副作用）。
if (process.argv[1]?.endsWith('normalize-content-collections.ts')) {
  normalizeGeneratedFile()
}
